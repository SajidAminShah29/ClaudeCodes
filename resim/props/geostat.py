"""Synthetic geostatistical fields for heterogeneous test models.

Stationary Gaussian random fields are generated by circulant embedding
(FFT): the covariance is laid out on a padded periodic grid, its spectrum is
computed, and white noise is filtered by the square root of that spectrum.
Padding by at least one correlation range suppresses wrap-around.
"""

from __future__ import annotations

import numpy as np
from scipy import fft
from scipy.special import ndtri


def covariance(h: np.ndarray, kind: str) -> np.ndarray:
    """Unit-sill covariance as a function of range-scaled distance ``h``.

    ``range`` is the practical range (covariance ~5% for exponential/gaussian).
    """
    if kind == "spherical":
        return np.where(h < 1.0, 1.0 - 1.5 * h + 0.5 * h**3, 0.0)
    if kind == "exponential":
        return np.exp(-3.0 * h)
    if kind == "gaussian":
        return np.exp(-3.0 * h**2)
    raise ValueError(f"unknown variogram type {kind!r} (spherical, exponential, gaussian)")


def gaussian_random_field(
    shape: tuple[int, int, int],
    spacing: tuple[float, float, float],
    kind: str = "spherical",
    ranges=(1.0, 1.0, 1.0),
    azimuth: float = 0.0,
    seed: int | None = None,
) -> np.ndarray:
    """Zero-mean, unit-variance Gaussian field of ``shape`` (nx, ny, nz).

    ``ranges`` = (major horizontal, minor horizontal, vertical) in metres.
    ``azimuth`` = direction of the major range, degrees clockwise from +y.
    """
    ranges = np.broadcast_to(np.asarray(ranges, dtype=float), (3,))
    if np.any(ranges <= 0):
        raise ValueError("variogram ranges must be positive")
    spacing = np.asarray(spacing, dtype=float)
    horizontal = max(ranges[0], ranges[1])
    reach = (horizontal, horizontal, ranges[2])
    padded = tuple(
        fft.next_fast_len(int(n + np.ceil(r / h)) if n > 1 else 1) for n, r, h in zip(shape, reach, spacing)
    )

    # Signed periodic lags on the padded grid (sign matters for the rotation).
    sx = _signed_lag(padded[0], spacing[0])[:, None, None]
    sy = _signed_lag(padded[1], spacing[1])[None, :, None]
    sz = _signed_lag(padded[2], spacing[2])[None, None, :]
    az = np.deg2rad(azimuth)
    u = sx * np.sin(az) + sy * np.cos(az)  # along major direction
    v = sx * np.cos(az) - sy * np.sin(az)  # along minor direction
    h = np.sqrt((u / ranges[0]) ** 2 + (v / ranges[1]) ** 2 + (sz / ranges[2]) ** 2)

    spectrum = fft.fftn(covariance(h, kind)).real
    spectrum[spectrum < 0] = 0.0
    rng = np.random.default_rng(seed)
    noise = rng.standard_normal(padded)
    field = fft.ifftn(np.sqrt(spectrum) * fft.fftn(noise)).real
    return field[: shape[0], : shape[1], : shape[2]]


def _signed_lag(m: int, h: float) -> np.ndarray:
    idx = np.arange(m)
    return np.where(idx <= m // 2, idx, idx - m) * h


def transform(y: np.ndarray, mean: float, std: float, kind: str = "normal") -> np.ndarray:
    """Map a standard normal field to a target distribution with given mean / std."""
    if kind == "normal":
        return mean + std * y
    if kind == "lognormal":
        if mean <= 0:
            raise ValueError("lognormal transform requires a positive mean")
        sigma2 = np.log1p((std / mean) ** 2)
        return np.exp(np.log(mean) - sigma2 / 2 + np.sqrt(sigma2) * y)
    raise ValueError(f"unknown transform {kind!r} (normal, lognormal)")


def truncate(y: np.ndarray, proportions, codes=None) -> np.ndarray:
    """Truncated-Gaussian categorical field: threshold ``y`` by proportions."""
    p = np.asarray(proportions, dtype=float)
    if np.any(p < 0) or not np.isclose(p.sum(), 1.0):
        raise ValueError("proportions must be non-negative and sum to 1")
    codes = np.arange(1, p.size + 1) if codes is None else np.asarray(codes)
    if codes.size != p.size:
        raise ValueError("codes and proportions must have the same length")
    thresholds = ndtri(np.cumsum(p)[:-1])
    return codes[np.searchsorted(thresholds, y)]
